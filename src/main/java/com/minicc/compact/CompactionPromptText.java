package com.minicc.compact;

/**
 * 第⑤层自动压缩的摘要提示词（固定分段）。
 *
 * <p>要点有二：其一，强制模型**只输出文字、绝不调用工具**（mini-cc 的自动压缩是一次性受限调用，
 * 带不带工具都不希望它去真的执行）；其二，把摘要**固定分成九段**，其中第 6 段"全部用户消息"最关键——
 * 它要求模型逐条复述用户的原话，保证"用户到底要什么"不因摘要而丢失。
 *
 * <p>简化：完整版提示词还有 {@code <analysis>} 草稿块、partial / up_to 多个变体、自定义指令拼接等；
 * mini-cc 只取"无工具前言 + 九段结构"这条教学主干，用中文书写，便于学员对照理解。
 */
public final class CompactionPromptText {

    private CompactionPromptText() {
    }

    /** 自动压缩摘要提示词全文。 */
    public static final String SUMMARY_PROMPT = """
            重要：只用纯文本回答，不要调用任何工具（Read/Grep/Glob/Bash/Edit/Write 等一律不要用）。
            你已经拥有完成任务所需的全部上下文；任何工具调用都会被拒绝、并浪费这次机会。

            你的任务：为上面这段对话生成一份详尽的摘要，用于在上下文接近上限时替换较早的历史，
            让后续对话能够无缝继续。请特别关注用户的明确诉求，以及你此前采取的行动。

            摘要必须严格按下面九个小节组织，每节都要尽量完整准确：

            1. 主要请求与意图：完整捕捉用户所有明确的请求与意图。
            2. 关键技术概念：列出讨论到的重要技术概念、技术栈与框架。
            3. 涉及的文件与代码：逐一列出查看、修改或新建过的文件与代码片段，并说明为什么重要；
               对最近的改动尽量附上关键代码片段。
            4. 报错与修复：列出遇到的所有报错，以及你是如何修复的；尤其注意用户给出的纠正性反馈。
            5. 解题过程：记录已解决的问题，以及仍在进行中的排查。
            6. 全部用户消息：逐条列出所有**非工具结果**的用户消息原话。这一段最重要——它是理解用户反馈与
               意图变化的依据，务必完整、不要遗漏、不要改写。
            7. 未完成事项：列出用户明确要求、但尚未完成的任务。
            8. 当前正在做的工作：精确描述在本次摘要之前，你正在进行的具体工作（文件名、代码片段）。
            9. 可选的下一步：如果有，列出与"最近工作"直接相关的下一步；不要擅自开启新的、跑题的任务。

            请直接输出这九个小节的文字，不要有多余的开场白或结束语。
            """;
}
